#!/usr/bin/env node
// Focused smoke check for `greplica install --platform cline`.
// Verifies Cline-compatible guidance is generated under .clinerules, shared
// skills and a Cline plugin hook are installed, and user-authored Cline files survive.
//
// Hermetic: GREPLICA_HOME points at a temp dir so it never touches ~/.greplica.
// Usage: node scripts/smoke-cline-install.mjs [--keep-temp] [--result-json <path>]
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = findRepoRoot(scriptDir);
const cli = resolve(repoRoot, "dist/apps/cli/main.js");

const args = parseArgs(process.argv.slice(2));
const ownsTempDir = args.keepTemp !== true;
const tempDir = mkdtempSync(resolve(tmpdir(), "greplica-cline-smoke-"));
const workspace = resolve(tempDir, "repo");
const greplicaHome = resolve(tempDir, "home");
const env = { ...process.env, GREPLICA_HOME: greplicaHome };
delete env.GREPLICA_HOOK_DISABLE;

let checks = [];
try {
  if (!existsSync(cli)) throw new Error(`Built CLI not found at ${cli}. Run "npm run build" first.`);

  runOrThrow(["git", "init", "-q", workspace], repoRoot);

  checks.push(checkRuleInstall());
  checks.push(checkSkillsAndPlugin());
  checks.push(checkNonDestructiveReinstall());
} catch (error) {
  checks = [{ id: "smoke_script", passed: false, details: [error instanceof Error ? error.stack ?? error.message : String(error)] }];
} finally {
  const passed = checks.filter((check) => check.passed).length;
  const result = { success: passed === checks.length, passed_checks: passed, total_checks: checks.length, workspace, checks };
  const serialized = `${JSON.stringify(result, null, 2)}\n`;
  if (args.resultJson !== undefined) writeFileSync(args.resultJson, serialized);
  process.stdout.write(serialized);
  if (ownsTempDir) rmSync(tempDir, { recursive: true, force: true });
  process.exitCode = result.success ? 0 : 1;
}

function checkRuleInstall() {
  const details = [];
  const customRule = resolve(workspace, ".clinerules", "custom.md");
  mkdirSync(dirname(customRule), { recursive: true });
  writeFileSync(customRule, "custom rule\n", "utf8");

  const first = runOrThrow(["node", cli, "install", "--platform", "cline", "--embedding", "local"], workspace);
  const second = runOrThrow(["node", cli, "install", "--platform", "cline", "--embedding", "local"], workspace);
  const rulePath = resolve(workspace, ".clinerules", "greplica.md");

  if (!existsSync(rulePath)) details.push("expected .clinerules/greplica.md to be created");
  else {
    const rule = readFileSync(rulePath, "utf8");
    for (const pattern of [
      "Generated by Greplica",
      "greplica-bootstrap",
      "greplica graph context",
      "greplica-update-working-memory",
      ".cline/skills",
      "beforeModel",
    ]) {
      if (!rule.includes(pattern)) details.push(`generated rule missing ${JSON.stringify(pattern)}`);
    }
  }

  if (readFileSync(customRule, "utf8") !== "custom rule\n") details.push("existing .clinerules/custom.md was modified");
  for (const pattern of ["Installed Greplica for Cline", "Guidance:", ".clinerules/greplica.md", ".cline/plugins/greplica.ts", "Skills:", "Hooks: installed for beforeModel", "Reload or restart Cline"]) {
    if (!first.stdout.includes(pattern)) details.push(`install output missing ${JSON.stringify(pattern)}`);
  }
  if (!second.stdout.includes(".clinerules/greplica.md")) details.push("reinstall did not keep using the generated greplica.md rule");

  return { id: "cline_rule_install", passed: details.length === 0, details };
}

function checkSkillsAndPlugin() {
  const details = [];
  for (const skill of ["greplica-bootstrap", "greplica-update-working-memory"]) {
    const skillPath = resolve(workspace, ".cline/skills", skill, "SKILL.md");
    if (!existsSync(skillPath)) details.push(`missing skill ${skillPath}`);
  }

  const pluginPath = resolve(workspace, ".cline/plugins/greplica.ts");
  if (!existsSync(pluginPath)) {
    details.push(".cline/plugins/greplica.ts was not created");
  } else {
    const plugin = readFileSync(pluginPath, "utf8");
    for (const pattern of ["Generated by Greplica", "AgentPlugin", "beforeModel", "greplica graph context"]) {
      if (!plugin.includes(pattern)) details.push(`plugin missing ${JSON.stringify(pattern)}`);
    }
  }

  return { id: "skills_and_plugin_installed", passed: details.length === 0, details };
}

function checkNonDestructiveReinstall() {
  const details = [];
  const safeWorkspace = resolve(tempDir, "repo-with-user-rule");
  runOrThrow(["git", "init", "-q", safeWorkspace], repoRoot);
  const userRule = resolve(safeWorkspace, ".clinerules", "greplica.md");
  mkdirSync(dirname(userRule), { recursive: true });
  writeFileSync(userRule, "user-authored greplica rule\n", "utf8");

  const output = runOrThrow(["node", cli, "install", "--platform", "cline", "--embedding", "local"], safeWorkspace).stdout;
  const fallbackRule = resolve(safeWorkspace, ".clinerules", "greplica-1.md");

  if (readFileSync(userRule, "utf8") !== "user-authored greplica rule\n") {
    details.push("user-authored .clinerules/greplica.md was overwritten");
  }
  if (!existsSync(fallbackRule)) details.push("expected fallback .clinerules/greplica-1.md to be created");
  else if (!readFileSync(fallbackRule, "utf8").includes("Generated by Greplica")) {
    details.push("fallback rule is missing the Greplica marker");
  }
  if (!output.includes(".clinerules/greplica-1.md")) details.push("install output did not report fallback rule path");

  const userPlugin = resolve(safeWorkspace, ".cline/plugins/greplica.ts");
  mkdirSync(dirname(userPlugin), { recursive: true });
  writeFileSync(userPlugin, "export default { name: 'user-plugin' };\n", "utf8");
  runOrThrow(["node", cli, "install", "--platform", "cline", "--embedding", "local"], safeWorkspace);
  if (readFileSync(userPlugin, "utf8") !== "export default { name: 'user-plugin' };\n") {
    details.push("user-authored .cline/plugins/greplica.ts was overwritten");
  }
  const fallbackPlugin = resolve(safeWorkspace, ".cline/plugins/greplica-1.ts");
  if (!existsSync(fallbackPlugin)) details.push("expected fallback .cline/plugins/greplica-1.ts to be created");
  else if (!readFileSync(fallbackPlugin, "utf8").includes("Generated by Greplica")) {
    details.push("fallback plugin is missing the Greplica marker");
  }

  return { id: "cline_rule_non_destructive", passed: details.length === 0, details };
}

function run(commandArgs, cwd, input) {
  return spawnSync(commandArgs[0], commandArgs.slice(1), { cwd, env, input, encoding: "utf8" });
}

function runOrThrow(commandArgs, cwd, input) {
  const result = run(commandArgs, cwd, input);
  if (result.status !== 0) {
    throw new Error(`Command failed (${result.status}): ${commandArgs.join(" ")}\n${result.stderr ?? ""}`);
  }
  return result;
}

function findRepoRoot(startDir) {
  let current = startDir;
  for (let depth = 0; depth < 8; depth += 1) {
    if (existsSync(resolve(current, "package.json")) && existsSync(resolve(current, "libs/install/platforms/cline.ts"))) return current;
    const parent = dirname(current);
    if (parent === current) break;
    current = parent;
  }
  throw new Error(`Could not find repo root from ${startDir}`);
}

function parseArgs(values) {
  const parsed = {};
  for (let index = 0; index < values.length; index += 1) {
    const value = values[index];
    if (value === "--result-json") parsed.resultJson = values[(index += 1)];
    else if (value === "--keep-temp") parsed.keepTemp = true;
    else throw new Error(`Unknown argument: ${value}`);
  }
  return parsed;
}
